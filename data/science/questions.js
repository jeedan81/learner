function makeQuestionSet(grade, diff, count = 10, unit = null) {
  let pool = QUESTIONS.filter(q => q.g === grade && (!unit || q.u === unit));
  const exact = shuffle(pool.filter(q => q.d === diff));
  const nearPool = shuffle(pool.filter(q => Math.abs(q.d - diff) === 1));
  const farPool = shuffle(pool.filter(q => Math.abs(q.d - diff) >= 2));
  let picked = [...exact, ...nearPool].slice(0, count);
  const gens = (GENERATORS[grade] || []).filter(g => !unit || g(diff).u === unit);
  // 계산 문제를 한두 개 섞어 매번 새로운 문제가 나오도록
  if (gens.length && picked.length >= count - 1) picked = picked.slice(0, count - 2);
  while (picked.length < count && gens.length) picked.push(gens[rnd(0, gens.length - 1)](diff));
  for (const q of farPool) { if (picked.length >= count) break; picked.push(q); }
  return shuffle(picked).map(q => {
    const order = shuffle(q.o.map((_, i) => i));
    return { ...q, o: order.map(i => q.o[i]), a: order.indexOf(q.a) };
  });
}

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

function unitsOf(grade) {
  return [...new Set(QUESTIONS.filter(q => q.g === grade).map(q => q.u))];
}
