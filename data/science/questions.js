const near = (x, unit) => {
  const set = new Set([x]);
  const muls = [2, 0.5, 1.5, 3, 4];
  for (const m of muls) { if (set.size >= 4) break; const v = +(x * m).toFixed(2); if (v !== x) set.add(v); }
  return [...set].slice(0, 4).map(v => `${v} ${unit}`);
};

